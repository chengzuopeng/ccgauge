#!/usr/bin/env node
/**
 * Build the Astro site for EdgeOne Pages.
 *
 * Why this exists instead of just running `pnpm site:build` there:
 *
 * EdgeOne auto-detects the framework by scanning the repo root, and this repo's
 * root IS a Next.js app (`next.config.mjs`, `middleware.ts`). So it loads
 * `@edgeone/opennextjs-pages` before it ever reads the build configuration —
 * "框架预设: Other" does not prevent this — builds the Astro site as told, then
 * runs the plugin's onBuild hook, which looks for `.next/required-server-files.json`
 * and fails the deploy:
 *
 *   [plugins][✘] Error executing onBuild hook: ENOENT ... .next/required-server-files.json
 *
 * There is no edgeone.json field to disable framework detection (checked against
 * both Tencent's docs and pages.edgeone.ai). So this removes the files the
 * detection keys on, then builds.
 *
 * IMPORTANT — the files are deliberately NOT restored after a successful build.
 * EdgeOne re-checks the project type AFTER the build command returns; putting
 * them back would hand detection the same evidence and change nothing. They are
 * restored only when the build fails, so an accidental local run doesn't leave a
 * mangled tree.
 *
 * This is a workaround against undocumented detection behaviour, so treat it as
 * load-bearing-but-brittle: if EdgeOne changes when it detects, this stops
 * working silently. The documented alternative is deploying prebuilt output with
 * `npx edgeone pages deploy site/dist -n <project> -t <token>` from CI, which
 * never gives EdgeOne a repo to inspect.
 */

import { execFileSync, spawnSync } from 'node:child_process';
import { existsSync, rmSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

// `next-env.d.ts` is gitignored and regenerated by Next on the next build, so it
// needs no restore path. The other two are tracked, hence `git checkout --`.
const TARGETS = [
  { file: 'next.config.mjs', tracked: true },
  { file: 'middleware.ts', tracked: true },
  { file: 'next-env.d.ts', tracked: false },
];

function git(args, opts = {}) {
  return execFileSync('git', args, { cwd: ROOT, encoding: 'utf8', ...opts }).trim();
}

function insideGitRepo() {
  try {
    return git(['rev-parse', '--is-inside-work-tree'], { stdio: ['ignore', 'pipe', 'ignore'] }) === 'true';
  } catch {
    return false;
  }
}

const restorable = [];

/** Refuse to delete a tracked file that has edits — losing those is not a
 *  trade-off a build script gets to make on the user's behalf. */
function assertClean() {
  if (!insideGitRepo()) {
    throw new Error(
      'not a git checkout — refusing to delete Next.js config files, since there would be no way to restore them',
    );
  }
  const dirty = git(['status', '--porcelain', '--', ...TARGETS.filter((t) => t.tracked).map((t) => t.file)]);
  if (dirty) {
    throw new Error(
      `uncommitted changes in files this script deletes:\n${dirty}\n` +
        'Commit or stash them first. (This is why you are seeing this instead of losing the edits.)',
    );
  }
}

function hide() {
  for (const { file, tracked } of TARGETS) {
    const abs = resolve(ROOT, file);
    if (!existsSync(abs)) continue;
    rmSync(abs);
    if (tracked) restorable.push(file);
    console.log(`  removed ${file}`);
  }
}

function restore() {
  if (restorable.length === 0) return;
  git(['checkout', '--', ...restorable]);
  console.log(`  restored ${restorable.join(', ')}`);
  restorable.length = 0;
}

console.log('[edgeone] hiding Next.js markers so framework detection sees a static project');
try {
  assertClean();
} catch (err) {
  // A stack trace here is noise: every failure mode is a precondition the
  // operator has to fix, and this text is what lands in the CI log.
  console.error(`[edgeone] refusing to run — ${err.message}`);
  process.exit(1);
}
hide();

console.log('[edgeone] building the Astro site');
const build = spawnSync('pnpm', ['site:build'], { cwd: ROOT, stdio: 'inherit' });

if (build.status !== 0) {
  console.error('[edgeone] site build failed — restoring the files it removed');
  restore();
  process.exit(build.status ?? 1);
}

console.log(
  '\n[edgeone] site built. Next.js config files are left removed ON PURPOSE:\n' +
    '          EdgeOne re-detects the project type after this command returns.\n' +
    `          Restore locally with:  git checkout -- ${TARGETS.filter((t) => t.tracked)
      .map((t) => t.file)
      .join(' ')}`,
);
